const assert = require('node:assert/strict');
const o = require('./observing.js');
assert.equal(o.windChill(20, 30), 'Not applicable');
assert.equal(o.windChill(0, 0), 'Not applicable');
assert.equal(o.windChill(null, 20), 'Unavailable');
assert.equal(o.windChill(0, 20), '-5.2 C');
const rows = o.astroRows({init:'2026102606', dataseries:[{timepoint:3,seeing:2},{timepoint:6,seeing:3}]});
assert.equal(rows[0].time, Date.parse('2026-10-26T09:00:00Z'));
assert.equal(o.astroAt(rows, Date.parse('2026-10-25T09:00:00Z')), null);
assert.equal(o.astroAt(rows, Date.parse('2026-10-27T09:00:00Z')), null);
assert.equal(o.astroAt(rows, Date.parse('2026-10-26T11:00:00Z')).seeing, 3);
assert.equal(o.category(-9999, 'seeing'), 'Unavailable');
assert.equal(o.category(2, 'transparency'), '0.3-0.4');
const kp = o.kpRows([{time_tag:'2026-10-26T00:00:00',kp:2,observed:'predicted'}]);
assert.equal(o.kpAt(kp, Date.parse('2026-10-26T02:59:00Z')).value, 2);
assert.equal(o.kpAt(kp, Date.parse('2026-10-26T03:00:00Z')), undefined);
assert.equal(o.kpRows([{time_tag:'2026-10-26T00:00:00',kp:null}]).length,0);
assert.equal(o.kpRows([['time_tag','kp','observed'],['2026-10-26 00:00:00','2.33','estimated']])[0].value,2.33);
global.Astronomy = require('./astronomy.browser.min.js');
const sky = o.sky(Date.parse('2026-10-26T18:00:00Z'), 28.61, 77.21);
assert.match(sky.moon, /% lit/);
assert.equal(sky.planets.includes('NaN'), false);
assert.notEqual(sky.planets, 'Unavailable');
console.log('Passed: wind chill, missing data, forecast horizons, Kp formats, moon and planets.');
